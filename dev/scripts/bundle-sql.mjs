// Concatenate the migrations + Supabase-only setup into platform/supabase/all.sql (one paste in the SQL editor).
//   node scripts/bundle-sql.mjs
import fs from 'node:fs';
import path from 'node:path';
import { SQL_DIR } from '../db.js';
const mig = fs.readdirSync(path.join(SQL_DIR, 'migrations')).filter((f) => f.endsWith('.sql')).sort();
const parts = mig.map((f) => `-- ═════════ ${f} ═════════\n${fs.readFileSync(path.join(SQL_DIR, 'migrations', f), 'utf8')}`);
parts.push(`-- ═════════ supabase_only.sql ═════════\n${fs.readFileSync(path.join(SQL_DIR, 'supabase_only.sql'), 'utf8')}`);
const out = `-- Mamar Booking · everything for a fresh Supabase project, in order. GENERATED by dev/scripts/bundle-sql.mjs — edit the source files.\n\n${parts.join('\n\n')}`;
fs.writeFileSync(path.join(SQL_DIR, 'all.sql'), out);
console.log(`wrote all.sql (${mig.length} migrations + supabase_only, ${(out.length / 1024).toFixed(0)} KB)`);
