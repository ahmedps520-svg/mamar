// Supabase Edge Function "notify" (deploy with "Verify JWT" OFF — it checks its own signature).
//
//  POST  ← the database (pg_net trigger on public.notifications), header x-hook-secret
//          → Web Push to every device where Ahmed turned notifications on (+ email if configured)
//  POST  {action:'test_email'} + the admin's own sign-in token → sends one test email now and
//          returns exactly what Resend said (the admin's "Send a test email" button)
//  GET   ?vapid=1 → { vapid_public } so the admin can subscribe for push
//
// Nothing to paste into Secrets for push: on first run the function generates its own VAPID keys and
// stores them in public.app_secrets through svc_secret_set; the webhook secret was generated by the database.
// Email: set RESEND_API_KEY + NOTIFY_EMAIL (+ FROM_EMAIL) in Edge Function secrets.
// SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are provided automatically.
// Later: a native iOS app adds an APNs sender next to webpush below.
import webpush from 'npm:web-push@3.6.7';

const SB_URL = Deno.env.get('SUPABASE_URL')!;
const SB_KEY = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!;
const CORS = {
  'access-control-allow-origin': '*',
  'access-control-allow-headers': 'authorization, apikey, content-type, x-hook-secret',
  'access-control-allow-methods': 'GET, POST, OPTIONS',
};

async function rpc(name: string, p: unknown) {
  const r = await fetch(`${SB_URL}/rest/v1/rpc/${name}`, {
    method: 'POST',
    headers: { apikey: SB_KEY, authorization: `Bearer ${SB_KEY}`, 'content-type': 'application/json' },
    body: JSON.stringify({ p }),
  });
  if (!r.ok) throw new Error(`${name}: ${r.status} ${await r.text()}`);
  return r.json();
}

let vapid: { publicKey: string; privateKey: string } | null = null;
async function vapidKeys() {
  if (vapid) return vapid;
  let stored = (await rpc('svc_secret_get', { key: 'vapid' })).value;
  if (!stored) {
    const fresh = webpush.generateVAPIDKeys();
    stored = (await rpc('svc_secret_set', { key: 'vapid', value: JSON.stringify(fresh) })).value;   // first writer wins
  }
  vapid = JSON.parse(stored);
  webpush.setVapidDetails('mailto:contact@mamar.site', vapid!.publicKey, vapid!.privateKey);
  return vapid!;
}

// Send one email through Resend; returns { ok, id?, error? } with Resend's own message on failure.
async function resend(to: string, subject: string, html: string, text: string) {
  const key = Deno.env.get('RESEND_API_KEY');
  if (!key) return { ok: false, error: 'RESEND_API_KEY is not set in Edge Function secrets' };
  if (!to) return { ok: false, error: 'NOTIFY_EMAIL is not set in Edge Function secrets' };
  const from = Deno.env.get('FROM_EMAIL') || 'Mamar <onboarding@resend.dev>';
  const r = await fetch('https://api.resend.com/emails', {
    method: 'POST', headers: { authorization: `Bearer ${key}`, 'content-type': 'application/json' },
    body: JSON.stringify({ from, to: [to], subject, html, text }),
  });
  const d = await r.json().catch(() => ({}));
  return r.ok ? { ok: true, id: d.id, to, from } : { ok: false, to, from, error: d.message || d.name || `HTTP ${r.status}` };
}

// Is the caller a signed-in Mamar admin? Their own sign-in token, checked by the database.
async function isAdmin(req: Request) {
  const auth = req.headers.get('authorization') || '';
  if (!auth.startsWith('Bearer ')) return false;
  const r = await fetch(`${SB_URL}/rest/v1/rpc/own_me`, {
    method: 'POST', headers: { apikey: SB_KEY, authorization: auth, 'content-type': 'application/json' },
    body: JSON.stringify({ p: {} }),
  });
  if (!r.ok) return false;
  return (await r.json()).is_admin === true;
}

const esc = (s: unknown) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]!));
const sar = (h: number | null) => (h == null ? 'Custom quote' : `${(h / 100).toLocaleString('en-US')} SAR`);

function email(n: any) {
  const note = n.notification;
  const r = n.request;
  const rows = r ? (r.estimate?.lines || []).map((l: any) =>
    `<tr><td style="padding:6px 0;color:#444">${esc(l.label_en)}${l.qty > 1 ? ` × ${l.qty}` : ''}</td>
     <td style="padding:6px 0;text-align:right">${l.quote ? 'Custom quote' : l.amount_halalas ? sar(l.amount_halalas) : 'Included'}</td></tr>`).join('') : '';
  const html = `<!doctype html><meta charset="utf-8"><div style="font:15px/1.5 -apple-system,Segoe UI,sans-serif;max-width:560px;margin:auto;padding:24px;color:#111">
  <p style="color:#FF4A2B;font-weight:600;letter-spacing:.08em;text-transform:uppercase;font-size:12px;margin:0 0 8px">Mamar</p>
  <h1 style="font-size:20px;margin:0 0 4px">${esc(note.title_en)}</h1><p style="margin:0 0 16px;color:#555">${esc(note.body_en)}</p>
  ${r ? `<p style="margin:0 0 16px"><b>${esc(r.contact_name)}</b> · ${esc(r.phone)}${r.email ? ` · ${esc(r.email)}` : ''}<br>Ref ${esc(r.ref)}</p>
  <table style="width:100%;border-collapse:collapse;border-top:1px solid #eee">${rows}
  <tr><td style="padding:10px 0;border-top:1px solid #111"><b>Setup estimate</b></td><td style="padding:10px 0;border-top:1px solid #111;text-align:right"><b>${sar(r.setup_halalas)}</b></td></tr>
  ${r.plan_code ? `<tr><td style="padding:6px 0;color:#444">Care plan (${esc(r.plan_interval)})</td><td style="text-align:right">${sar(r.plan_halalas)}</td></tr>` : ''}</table>` : ''}
  <p style="margin:24px 0 0"><a href="https://mamar.site${esc(note.url)}" style="background:#111;color:#fff;padding:10px 16px;border-radius:8px;text-decoration:none">Open in admin</a></p></div>`;
  return { subject: note.title_en, html, text: `${note.title_en}\n${note.body_en}\nhttps://mamar.site${note.url}` };
}

function testEmail() {
  const when = new Date().toLocaleString('en-GB', { timeZone: 'Asia/Riyadh' });
  const html = `<!doctype html><meta charset="utf-8"><div style="font:15px/1.6 -apple-system,Segoe UI,sans-serif;max-width:520px;margin:auto;padding:24px;color:#111">
  <p style="color:#FF4A2B;font-weight:600;letter-spacing:.08em;text-transform:uppercase;font-size:12px;margin:0 0 8px">Mamar</p>
  <h1 style="font-size:20px;margin:0 0 8px">Your booking emails work.</h1>
  <p style="margin:0 0 12px;color:#555">Sent ${esc(when)} (Jeddah). New setup requests will arrive at this address too.</p>
  <p dir="rtl" style="margin:0;color:#555">رسائل البريد تعمل. ستصلك طلبات الأنظمة الجديدة على هذا العنوان أيضاً.</p></div>`;
  return { subject: 'Test email from Mamar', html, text: `Your booking emails work. Sent ${when} (Jeddah).` };
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response(null, { headers: CORS });
  try {
    if (req.method === 'GET') {
      const k = await vapidKeys();
      return Response.json({ vapid_public: k.publicKey }, { headers: CORS });
    }

    const body = await req.json().catch(() => null);

    // The admin's "Send a test email" button.
    if (body?.action === 'test_email') {
      if (!(await isAdmin(req))) return Response.json({ ok: false, error: 'NOT_ALLOWED' }, { status: 403, headers: CORS });
      const m = testEmail();
      const out = await resend(Deno.env.get('NOTIFY_EMAIL') || '', m.subject, m.html, m.text);
      return Response.json(out, { status: out.ok ? 200 : 400, headers: CORS });
    }

    // The database, for a new row in public.notifications.
    const expected = (await rpc('svc_secret_get', { key: 'hook_secret' })).value;
    if (!expected || req.headers.get('x-hook-secret') !== expected) return new Response('forbidden', { status: 403 });
    const id = body?.record?.id;
    if (!id) return new Response('no record', { status: 400 });

    await vapidKeys();
    const n = await rpc('svc_notification', { id });
    const note = n.notification;
    let pushed = 0;
    for (const t of n.targets) {
      const ar = t.lang !== 'en';
      const payload = JSON.stringify({ title: ar ? note.title_ar : note.title_en, body: ar ? note.body_ar : note.body_en,
        url: note.url, tag: `mamar-${note.kind}-${note.ref_id || note.id}`, lang: t.lang });
      try {
        await webpush.sendNotification({ endpoint: t.endpoint, keys: t.keys }, payload, { TTL: 86400, urgency: 'high' });
        pushed++;
      } catch (e: any) {
        if (e?.statusCode === 404 || e?.statusCode === 410) await rpc('svc_push_gone', { endpoint: t.endpoint });
      }
    }

    let emailed = false;
    let email_error: string | undefined;
    if (Deno.env.get('RESEND_API_KEY') && Deno.env.get('NOTIFY_EMAIL')) {
      const m = email(n);
      const out = await resend(Deno.env.get('NOTIFY_EMAIL')!, m.subject, m.html, m.text);
      emailed = out.ok;
      email_error = out.error;
    }
    return Response.json({ ok: true, pushed, emailed, ...(email_error ? { email_error } : {}) }, { headers: CORS });
  } catch (e: any) {
    return Response.json({ ok: false, error: String(e?.message || e) }, { status: 500, headers: CORS });
  }
});
